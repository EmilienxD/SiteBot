#!/usr/bin/env node
// Generates reference/configuration.md from the config schema.
//
// The source is `emitJsonSchema()` from @sitebot/config — the same JSON Schema
// that editors use for autocomplete, itself generated from the Zod schema the
// loader validates with. So the page, the editor hints and the validator
// cannot disagree. CI runs this with --check and fails if the committed page
// differs from what the schema produces.
//
//   node scripts/config-reference.mjs           write the page
//   node scripts/config-reference.mjs --check   exit 1 if it is out of date

import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const OUTPUT = new URL('../reference/configuration.md', import.meta.url)
const MAX_SAFE = Number.MAX_SAFE_INTEGER

/** Top-level sections, in the order docs/02 introduces them. */
const INTRO = `---
outline: [2, 3]
---

# Configuration reference

<!-- Generated by apps/docs/scripts/config-reference.mjs from the config schema. Do not edit by hand. -->

Every key \`chatbot.config.*\` accepts, with its type, default and validation rules. This page is
generated from the same schema the loader validates with, so it can't list a key the loader rejects,
or miss one it accepts.

Unknown keys are errors, not warnings. Any string value can use \`\${env.NAME}\` or
\`\${env.NAME:-default}\` to read from the environment. For how the pieces fit together, see the
[configuration guide](/guide/configuration).
`

export function renderConfigReference(schema) {
  const out = [INTRO]
  const required = new Set(schema.required ?? [])
  for (const [key, node] of Object.entries(schema.properties)) {
    out.push(`## \`${key}\`${required.has(key) ? ' <Badge type="warning" text="required" />' : ''}`)
    out.push('')
    // A leaf's description is already in its one table row.
    const leaf = !node.properties && !unionVariants(node) && node.type !== 'array'
    if (node.description && !leaf) out.push(escapeText(sentence(node.description)), '')
    renderNode(out, key, node, 3)
  }
  return `${out.join('\n').replace(/\n{3,}/g, '\n\n').trim()}\n`
}

/** Emit the rows for `node` at `path`, and a subsection per union variant. */
function renderNode(out, path, node, depth) {
  const variants = unionVariants(node)
  if (variants) {
    renderUnion(out, path, node, variants, depth)
    return
  }
  const rows = []
  const sections = []
  collectRows(rows, sections, path, node, false)
  if (rows.length > 0) out.push(...table(rows), '')
  for (const section of sections) section(out, depth)
}

/**
 * Walk objects into dotted rows. Anything that is itself a union of objects
 * (a nested `executor`, `server`, `store`) becomes a deferred subsection so
 * the parent table stays one level of detail.
 */
function collectRows(rows, sections, path, node, parentRequired) {
  const items = node.type === 'array' ? node.items : undefined
  if (items && unionVariants(items)) {
    rows.push(row(path, node, parentRequired))
    sections.push((out, depth) => renderNode(out, `${path}[]`, items, depth))
    return
  }
  if (items && items.type === 'object' && items.properties) {
    rows.push(row(path, node, parentRequired))
    const required = new Set(items.required ?? [])
    for (const [key, child] of Object.entries(items.properties))
      collectRows(rows, sections, `${path}[].${key}`, child, required.has(key))
    return
  }
  if (unionVariants(node)) {
    rows.push(row(path, node, parentRequired))
    sections.push((out, depth) => renderNode(out, path, node, depth))
    return
  }
  if (node.type === 'object' && node.properties) {
    // The object's own description would otherwise be lost to its children.
    if (node.description) rows.push(row(path, node, parentRequired))
    const required = new Set(node.required ?? [])
    for (const [key, child] of Object.entries(node.properties))
      collectRows(rows, sections, `${path}.${key}`, child, required.has(key))
    return
  }
  rows.push(row(path, node, parentRequired))
}

function renderUnion(out, path, node, variants, depth) {
  const { discriminator, options } = variants
  const heading = '#'.repeat(Math.min(depth, 6))
  if (node.default !== undefined) out.push(`Default: \`${compact(node.default)}\``, '')
  const labels = options.map((option) => variantLabel(option, discriminator))
  out.push(
    discriminator
      ? `One of ${options.length} shapes, chosen by \`${discriminator}\`.`
      : `One of ${options.length} shapes.`,
    '',
  )
  options.forEach((option, index) => {
    out.push(`${heading} \`${path}\` — ${labels[index]}`, '')
    if (option.description) out.push(escapeText(sentence(option.description)), '')
    const rows = []
    const sections = []
    const required = new Set(option.required ?? [])
    for (const [key, child] of Object.entries(option.properties ?? {}))
      collectRows(rows, sections, `${path}.${key}`, child, required.has(key))
    if (rows.length > 0) out.push(...table(rows), '')
    for (const section of sections) section(out, depth + 1)
  })
}

/** Keys that select a variant, in the order we trust them. */
const DISCRIMINATORS = ['type', 'from', 'transport']

/** A union of object shapes, and the property that tells them apart, if any. */
function unionVariants(node) {
  const options = node.oneOf ?? node.anyOf
  if (!options || !options.every((option) => option.type === 'object' && option.properties))
    return undefined
  const discriminator = DISCRIMINATORS.find((key) =>
    options.every((option) => tagOf(option.properties[key]) !== undefined),
  )
  return { discriminator, options }
}

/** `const` or `enum` as the text a config file would contain. */
function tagOf(node) {
  if (node?.const !== undefined) return String(node.const)
  if (node?.enum !== undefined) return node.enum.join(' | ')
  return undefined
}

/**
 * `type: sqlite` when the union has a shared discriminator. Otherwise the
 * variant's own constant keys (`from: mcp`), and "anything else" for the
 * shape that has none — the `tools[]` split between an MCP import and a tool.
 */
function variantLabel(option, discriminator) {
  if (discriminator) return `\`${discriminator}: ${tagOf(option.properties[discriminator])}\``
  const constants = Object.entries(option.properties)
    .filter(([, child]) => child.const !== undefined)
    .map(([key, child]) => `\`${key}: ${child.const}\``)
  return constants.length > 0 ? constants.join(', ') : 'anything else'
}

function row(path, node, isRequired) {
  return {
    key: `\`${path}\`${isRequired ? ' <Badge type="warning" text="required" />' : ''}`,
    type: `\`${typeOf(node)}\``,
    default: node.default === undefined ? '' : `\`${compact(node.default)}\``,
    notes: [node.description ? escapeText(sentence(node.description)) : '', rules(node)]
      .filter(Boolean)
      .join(' '),
  }
}

function typeOf(node) {
  if (node.const !== undefined) return JSON.stringify(node.const)
  if (node.enum) return node.enum.map((value) => JSON.stringify(value)).join(' | ')
  const options = node.oneOf ?? node.anyOf
  if (options) {
    if (unionVariants(node)) return 'object'
    return [...new Set(options.map(typeOf))].join(' | ')
  }
  if (node.type === 'array') return `${wrap(typeOf(node.items ?? {}))}[]`
  if (node.type === 'object') {
    if (node.properties) return 'object'
    if (node.additionalProperties && typeof node.additionalProperties === 'object')
      return `Record<string, ${typeOf(node.additionalProperties)}>`
    return 'object'
  }
  if (node.type === 'integer') return 'integer'
  return node.type ?? 'any'
}

function wrap(type) {
  return type.includes('|') ? `(${type})` : type
}

function rules(node) {
  const parts = []
  if (node.minLength !== undefined && node.minLength > 0)
    parts.push(node.minLength === 1 ? 'non-empty' : `at least ${node.minLength} characters`)
  if (node.maxLength !== undefined) parts.push(`at most ${node.maxLength} characters`)
  if (node.exclusiveMinimum !== undefined) parts.push(`> ${node.exclusiveMinimum}`)
  if (node.minimum !== undefined) parts.push(`≥ ${node.minimum}`)
  if (node.maximum !== undefined && node.maximum !== MAX_SAFE) parts.push(`≤ ${node.maximum}`)
  if (node.minItems !== undefined && node.minItems > 0) parts.push(`at least ${node.minItems} items`)
  if (node.maxItems !== undefined) parts.push(`at most ${node.maxItems} items`)
  if (node.pattern) parts.push(`matches \`${node.pattern}\``)
  return parts.length > 0 ? `_${parts.join(', ')}._` : ''
}

function table(rows) {
  const cell = (text) => text.replace(/\|/g, '\\|').replace(/\n+/g, ' ')
  return [
    '| Key | Type | Default | Notes |',
    '| --- | --- | --- | --- |',
    ...rows.map(
      (entry) =>
        `| ${cell(entry.key)} | ${cell(entry.type)} | ${cell(entry.default)} | ${cell(entry.notes)} |`,
    ),
  ]
}

function compact(value) {
  const text = JSON.stringify(value)
  return text.length > 60 ? `${text.slice(0, 57)}…` : text
}

/**
 * Schema descriptions are plain text, but VitePress compiles each page as a
 * Vue template: `<string>` would open an element and `{{identity.sub}}` would
 * interpolate. Inline code is left alone — Markdown already escapes it.
 */
function escapeText(text) {
  return text
    .split(/(`[^`]*`)/)
    .map((part, index) =>
      index % 2 === 1
        ? part
        : part.replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\{\{/g, '&#123;&#123;'),
    )
    .join('')
}

function sentence(text) {
  const trimmed = text.trim()
  return /[.!?:)]$/.test(trimmed) ? trimmed : `${trimmed}.`
}

async function main() {
  const { emitJsonSchema } = await import('@sitebot/config')
  const page = renderConfigReference(emitJsonSchema())
  if (process.argv.includes('--check')) {
    const current = await readFile(OUTPUT, 'utf8').catch(() => '')
    if (current !== page) {
      console.error(
        'reference/configuration.md is out of date with the config schema.\n' +
          'Run `pnpm --filter @sitebot/docs reference` and commit the result.',
      )
      process.exit(1)
    }
    return
  }
  await writeFile(OUTPUT, page)
}

// Run when invoked as a script; stay inert when imported by the tests.
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main()
